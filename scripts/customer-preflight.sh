#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
CUSTOMER_DIR="$REPO_DIR/deploy/customer"
CUSTOMER_ENV="${GOMBEY_CUSTOMER_ENV_PATH:-$CUSTOMER_DIR/.env}"

fail() {
  echo "Customer deployment preflight failed: $*" >&2
  exit 1
}

[[ -f "$CUSTOMER_ENV" ]] || fail "deploy/customer/.env is missing; run scripts/customer-init.sh first"
if ENV_MODE="$(stat -c '%a' "$CUSTOMER_ENV" 2>/dev/null)"; then
  :
elif ENV_MODE="$(stat -f '%Lp' "$CUSTOMER_ENV" 2>/dev/null)"; then
  :
else
  fail "could not check deploy/customer/.env permissions"
fi
[[ "$ENV_MODE" == "600" ]] || fail "deploy/customer/.env must be mode 600; run chmod 600 deploy/customer/.env"
grep -q '^ALLOW_REGISTRATION=false$' "$CUSTOMER_ENV" || fail "public registration must remain disabled"
grep -q '^ALLOW_PASSWORD_RESET=false$' "$CUSTOMER_ENV" || fail "password reset must remain disabled until secure email is configured"

# Do not let a staging-only domain pass the production preflight. Read the two
# values as plain text instead of sourcing the environment file as shell code.
SITE_DOMAIN="$(sed -n 's/^SITE_DOMAIN=//p' "$CUSTOMER_ENV" | head -n 1)"
ACME_EMAIL="$(sed -n 's/^ACME_EMAIL=//p' "$CUSTOMER_ENV" | head -n 1)"
COMPOSE_PROJECT_NAME="$(sed -n 's/^COMPOSE_PROJECT_NAME=//p' "$CUSTOMER_ENV" | head -n 1)"
PROJECT_NAME_SCHEME="$(sed -n 's/^GOMBEY_PROJECT_NAME_SCHEME=//p' "$CUSTOMER_ENV" | head -n 1)"
HOSTNAME_RE='^([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?$'
EMAIL_RE='^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
if [[ ! "$SITE_DOMAIN" =~ $HOSTNAME_RE || "$SITE_DOMAIN" =~ ^[0-9.]+$ ]]; then
  fail "SITE_DOMAIN must be a public hostname, not a URL or IP address"
fi
[[ "$ACME_EMAIL" =~ $EMAIL_RE ]] || fail "ACME_EMAIL must be a valid address for certificate notices"

is_reserved_domain() {
  local domain
  domain="$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')"
  case "$domain" in
    *.test|*.example|*.invalid|*.localhost|*.local|*.internal|\
    example.com|example.net|example.org|*.example.com|*.example.net|*.example.org)
      return 0
      ;;
  esac
  return 1
}

is_reserved_domain "$SITE_DOMAIN" && fail "SITE_DOMAIN uses a reserved testing/example domain; set a real public hostname"
ACME_DOMAIN="${ACME_EMAIL##*@}"
is_reserved_domain "$ACME_DOMAIN" && fail "ACME_EMAIL uses a reserved testing/example domain; set a real deliverable email address"

# New deployments use a collision-resistant Docker resource namespace derived
# from the canonical hostname. Keep validating the legacy naming convention
# for pre-existing deployments so a routine update cannot create fresh empty
# volumes by changing their Compose project name.
DOMAIN_CANONICAL="$(printf '%s' "$SITE_DOMAIN" | tr '[:upper:]' '[:lower:]')"
case "$PROJECT_NAME_SCHEME" in
  sha256-v1)
    PROJECT_SUFFIX="$(printf '%s' "$DOMAIN_CANONICAL" | tr '.-' '__' | tr -cd 'a-z0-9_' | cut -c1-22)"
    DOMAIN_HASH="$(printf '%s' "$DOMAIN_CANONICAL" | openssl dgst -sha256 | awk '{print substr($NF, 1, 20)}')"
    EXPECTED_PROJECT_NAME="gombey_${PROJECT_SUFFIX:-customer}_${DOMAIN_HASH}"
    [[ "$COMPOSE_PROJECT_NAME" == "$EXPECTED_PROJECT_NAME" ]] || \
      fail "COMPOSE_PROJECT_NAME does not match SITE_DOMAIN; initialize a fresh per-customer deployment"
    ;;
  "")
    # Legacy .env files predate GOMBEY_PROJECT_NAME_SCHEME. Preserve their
    # exact old domain-derived value; never rewrite it during preflight.
    LEGACY_PROJECT_SUFFIX="$(printf '%s' "$DOMAIN_CANONICAL" | tr '.-' '__' | tr -cd 'a-z0-9_' | cut -c1-30)"
    LEGACY_PROJECT_NAME="gombey_${LEGACY_PROJECT_SUFFIX:-customer}"
    [[ "$COMPOSE_PROJECT_NAME" == "$LEGACY_PROJECT_NAME" ]] || \
      fail "COMPOSE_PROJECT_NAME does not match the legacy SITE_DOMAIN naming rule"
    ;;
  *)
    fail "unsupported GOMBEY_PROJECT_NAME_SCHEME; use a supported deployment initializer"
    ;;
esac

for setting in OPENAI_API_KEY OPENAI_MODELS ANTHROPIC_API_KEY ANTHROPIC_MODELS GOOGLE_KEY GOOGLE_MODELS OPENROUTER_KEY RAG_OPENAI_API_KEY RAG_OPENAI_BASEURL EMBEDDINGS_MODEL; do
  setting_line="$(grep -m 1 "^${setting}=" "$CUSTOMER_ENV" || true)"
  [[ -n "$setting_line" && "${setting_line#*=}" != "" ]] || fail "required provider setting ${setting} is missing or empty"
done
if grep -Eq 'REPLACE_ME|REPLACE_WITH_CUSTOMER_OWNED_EMBEDDINGS_API_KEY|chat\.customer\.example|ops@example\.com' "$CUSTOMER_ENV"; then
  fail "replace the sample domain/email and the customer-owned embeddings API key placeholder"
fi

# Secrets generated by customer-init.sh are distinct, cryptographically random
# hex values. Fail closed if a manual edit leaves one blank, weak, malformed, or
# accidentally copied from another setting. Never print the secret values.
SECURITY_SECRET_VALUES="|"
for setting in MONGO_ROOT_PASSWORD POSTGRES_PASSWORD MEILI_MASTER_KEY JWT_SECRET JWT_REFRESH_SECRET CREDS_KEY CREDS_IV; do
  setting_count="$(grep -c "^${setting}=" "$CUSTOMER_ENV" || true)"
  [[ "$setting_count" == "1" ]] || fail "security secret ${setting} must appear exactly once"
  secret_value="$(sed -n "s/^${setting}=//p" "$CUSTOMER_ENV" | head -n 1)"
  expected_length=64
  [[ "$setting" == "CREDS_IV" ]] && expected_length=32
  [[ "${#secret_value}" == "$expected_length" && "$secret_value" =~ ^[A-Fa-f0-9]+$ ]] || \
    fail "security secret ${setting} must be ${expected_length} hexadecimal characters"
  case "$SECURITY_SECRET_VALUES" in
    *"|${secret_value}|"*) fail "security secrets must be unique; ${setting} duplicates another secret" ;;
  esac
  SECURITY_SECRET_VALUES="${SECURITY_SECRET_VALUES}${secret_value}|"
done

command -v python3 >/dev/null 2>&1 || fail "python3 is required to inspect the rendered Compose configuration"
command -v openssl >/dev/null 2>&1 || fail "openssl is required to verify the Compose project namespace"

docker compose \
  --env-file "$CUSTOMER_ENV" \
  -f "$CUSTOMER_DIR/compose.yaml" \
  config --format json |
python3 -c '
import json
import sys

config = json.load(sys.stdin)
services = config.get("services", {})
expected_images = {
    "api": "ghcr.io/librechat-ai/librechat:v0.8.8",
    "caddy": "caddy:2.10.2-alpine",
    "mongodb": "mongo:8.0.20",
    "meilisearch": "getmeili/meilisearch:v1.35.1",
    "vectordb": "pgvector/pgvector:0.8.0-pg15-trixie",
    "rag_api": "gombey-ai/rag-api-fail-closed:0.8.8-gombey1",
}
for name, expected in expected_images.items():
    actual = services.get(name, {}).get("image")
    if actual != expected:
        print(
            f"Customer deployment preflight failed: {name} image differs from the validated template; "
            "review the upgrade and migration plan before changing pinned images.",
            file=sys.stderr,
        )
        raise SystemExit(1)

expected_rag_base = (
    "registry.librechat.ai/librechat-ai/librechat-rag-api-dev-lite:latest"
    "@sha256:3577689eedb1a74d4de69d70cee70b4cd42a9375ad74cdd5238ffc19a97392e3"
)
rag_build_args = services.get("rag_api", {}).get("build", {}).get("args", {})
if rag_build_args.get("UPSTREAM_RAG_IMAGE") != expected_rag_base:
    print(
        "Customer deployment preflight failed: RAG base image differs from the validated digest; "
        "review the compatibility patch before changing it.",
        file=sys.stderr,
    )
    raise SystemExit(1)

published = {name for name, service in services.items() if service.get("ports")}
if published != {"caddy"}:
    print("Customer deployment preflight failed: only Caddy may publish host ports.", file=sys.stderr)
    raise SystemExit(1)

expected_memory = {
    "api": 2 * 1024**3,
    "mongodb": 1 * 1024**3,
    "meilisearch": 512 * 1024**2,
    "vectordb": 1 * 1024**3,
    "rag_api": 1 * 1024**3,
}
for name, expected in expected_memory.items():
    service = services.get(name, {})
    try:
        actual_memory = int(service.get("mem_limit"))
    except (TypeError, ValueError):
        actual_memory = None
    if actual_memory != expected:
        print(
            f"Customer deployment preflight failed: {name} must have a {expected}-byte memory ceiling.",
            file=sys.stderr,
        )
        raise SystemExit(1)

ports = services["caddy"].get("ports", [])
allowed = {(80, 80, "tcp"), (443, 443, "tcp"), (443, 443, "udp")}
actual = set()
for port in ports:
    try:
        actual.add((int(port["published"]), int(port["target"]), port.get("protocol", "tcp")))
    except (KeyError, TypeError, ValueError):
        print("Customer deployment preflight failed: unrecognized Caddy port mapping.", file=sys.stderr)
        raise SystemExit(1)
if not actual or not actual.issubset(allowed) or (80, 80, "tcp") not in actual or (443, 443, "tcp") not in actual:
    print("Customer deployment preflight failed: Caddy may publish only TCP 80/443 and optional UDP 443.", file=sys.stderr)
    raise SystemExit(1)
'

echo "Preflight passed: secret-file checks are clean, Compose resolves, and only Caddy publishes web ports. This does not verify DNS, provider credentials, runtime health, or account isolation."
